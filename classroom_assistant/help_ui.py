def show_help(parent):
    window=tk.Toplevel(parent)
    window.title("❓ ДОВІДКА • Помічник учителя Classroom")
    from .window_ui import fit_work_window
    fit_work_window(window,"normal")
    window.minsize(770,530)
    outer=ttk.Frame(window,padding=10);outer.pack(fill="both",expand=True)
    ttk.Label(outer,text="ПОКРОКОВІ ІНСТРУКЦІЇ ДЛЯ ВЧИТЕЛЯ",font=("Segoe UI",14,"bold")).pack(anchor="w",pady=(0,8))
    notebook=ttk.Notebook(outer);notebook.pack(fill="both",expand=True)
    for heading,body in PAGES.items():
        frame=ttk.Frame(notebook)
        notebook.add(frame,text=heading)
        area=ScrolledText(frame,wrap="word",font=("Segoe UI",11),padx=15,pady=14,spacing2=3,spacing3=7)
        area.pack(fill="both",expand=True)
        area.insert("1.0",body)
        area.config(state="disabled",background="#f7f9fc")
    footer=ttk.Frame(outer);footer.pack(fill="x",pady=(8,0))
    for label,url in URLS:
        ttk.Button(footer,text="↗ "+label,command=lambda u=url:webbrowser.open(u)).pack(side="left",padx=3)
    ttk.Button(footer,text="Закрити довідку",command=window.destroy).pack(side="right",padx=3)
    window.transient(parent)
    return window
