def clean(text: str) -> str:
    text = re.sub(r"\[\d+\]|\[[а-яa-z]\]", "", text)
    text = re.sub(r"\s+", " ", text).strip(" \u00a0;,")
    return text


def shorten(text: str, limit: int = 84) -> str:
    text = clean(text)
    if len(text) <= limit:
        return text
    cut = text[:limit].rsplit(" ", 1)[0].rstrip(" ,;:—-")
    return cut + "…"


HEAD2 = re.compile(r"^==\s*([^=].*?)\s*==\s*$")
HEAD3 = re.compile(r"^===+\s*(.*?)\s*=+\s*$")
EVENT = re.compile(r"^(\d{1,4})(?:\s*(?:рік|року|р\.|до н\.\s?е\.))?\s*[—–-]\s*(.+)$")


def parse_extract(text: str) -> Facts:
    """Розбір простого тексту сторінки дня («== Події ==», «== Свята та пам'ятні дні ==»). Терпимий до відмінностей."""
    facts = Facts(source="Вікіпедія")
    section, skip = None, False
    for raw in (text or "").splitlines():
        line = raw.strip()
        if not line:
            continue
        two = HEAD2.match(line)
        if two:
            title = two.group(1).casefold()
            section = "events" if "поді" in title else ("holidays" if "свят" in title else None)
            skip = False
            continue
        three = HEAD3.match(line)
        if three:
            skip = section == "holidays" and any(word in three.group(1).casefold() for word in RELIGIOUS)
            continue
        if section == "events":
            found = EVENT.match(line)
            if found:
                facts.events.append((int(found.group(1)), shorten(found.group(2), 150)))
        elif section == "holidays" and not skip:
            if any(word in line.casefold() for word in RELIGIOUS):
                continue
            item = shorten(line)
            if len(item) >= 6:
                facts.holidays.append(item)
    return facts


def compose(facts: Facts | None, month: int, day: int, holidays_limit: int = 3, events_limit: int = 8) -> list:
    """Перелік для листочка: [('holiday'|'event', текст)].

    Події відбираються за значущістю для історика: спершу Друга світова війна та історія України (вбудований перелік
    і Вікіпедія), далі решта. Свята й події чергуються, українські свята — першими.
    """
    holidays, seen = [], []

    def add_holiday(text):
        key = text.casefold()
        if text and len(holidays) < holidays_limit and not any(key in s or s in key for s in seen):
            seen.append(key)
            holidays.append(("holiday", capfirst(text)))
    builtin = BUILTIN.get((month, day))
    if builtin:
        add_holiday(builtin)
    for text in sorted(facts.holidays if facts else [], key=lambda t: 0 if "україн" in t.casefold() else 1):
        add_holiday(text)
    pool, texts = [], set()
    for year, text in BUILTIN_EVENTS.get((month, day), []):
        pool.append((event_score(year, text, True), year, text))
        texts.add(text.casefold()[:40])
    for year, text in (facts.events if facts else []):
        if text.casefold()[:40] in texts:
            continue
        pool.append((event_score(year, text), year, text))
    pool.sort(key=lambda e: (-e[0], e[1]))
    events = [("event", f"{year} р. — {capfirst(text)}") for _, year, text in pool[:events_limit]]
    result = []
    for k in range(max(len(holidays), len(events))):
        result += holidays[k:k + 1] + events[k:k + 1]
    return result


