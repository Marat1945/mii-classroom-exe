def capfirst(text: str) -> str:
    """Подія у Вікіпедії починається після тире з малої літери: на листку речення має починатись з великої."""
    return text[:1].upper() + text[1:] if text else text


def event_score(year: int, text: str, builtin: bool = False) -> int:
    """Наскільки подія пасує вчителеві історії: Друга світова й історія України — першими."""
    low = text.casefold()
    score = 5 if builtin else 0
    if any(word in low for word in ("срср", "радянськ")):
        score += 2
    if year in WWII_YEARS:
        score += 6
    if any(word in low for word in WWII_WORDS):
        score += 3
    if any(word in low for word in UA_HISTORY_WORDS):
        score += 4
    return score


